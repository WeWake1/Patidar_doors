/**
 * Seed Supabase from the local catalogue (everything except the 12 Designer
 * Studio doors, which stay in code). One-time migration + a re-runnable
 * reference; idempotent (upsert by slug, images replaced per product).
 *
 * Migrated photos keep pointing at the committed /images/doors/* files and are
 * seeded as presentation='swing' (the signature door-open hover). Flip any that
 * look wrong swung to 'showcase' in the admin (live preview shows how each looks).
 *
 * Writes supabase/seed.sql — run it once via the Supabase dashboard SQL editor
 * (or `supabase db execute`). Re-running is safe (idempotent upserts).
 */
import { mkdir, writeFile } from 'node:fs/promises'
import { registerHooks } from 'node:module'
import path from 'node:path'

const ROOT = path.resolve(import.meta.dirname, '..')

// Node type-stripping runs the site's TS data modules, but its resolver wants
// explicit extensions — retry extensionless relative imports with `.ts`.
registerHooks({
  resolve(specifier, context, nextResolve) {
    try {
      return nextResolve(specifier, context)
    } catch (err) {
      if (specifier.startsWith('.') && !specifier.endsWith('.ts')) {
        try {
          return nextResolve(`${specifier}.ts`, context)
        } catch {
          throw err
        }
      }
      throw err
    }
  },
})
const { PRODUCTS } = await import('../src/data/products.ts')
const { WORLDS } = await import('../src/data/worlds.ts')

const slugify = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`)
const jsonb = (v) => `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`

// subcategory ordering from worlds.ts
const subOrder = new Map()
for (const w of WORLDS) w.subcategories.forEach((name, i) => subOrder.set(`${w.id}|${name}`, i))

/* Every product is the client's to manage now. The carve-out that used to sit
   here protected the 12 Designer Studio doors, whose artwork and prices lived
   in code; they were removed on 2026-08-20. */
const managed = PRODUCTS

// collect subcategories actually used
const subs = new Map()
for (const p of managed) {
  const key = `${p.world}|${p.sub}`
  if (!subs.has(key)) {
    subs.set(key, {
      world: p.world,
      name: p.sub,
      slug: slugify(p.sub),
      sort_order: subOrder.get(key) ?? 90,
    })
  }
}

const lines = ['-- GENERATED by scripts/seed-supabase.mjs — safe to re-run.', 'begin;', '']

for (const s of subs.values()) {
  lines.push(
    `insert into subcategories (world, name, slug, sort_order) values (${q(s.world)}, ${q(s.name)}, ${q(s.slug)}, ${s.sort_order})\n` +
      `  on conflict (world, slug) do update set name = excluded.name, sort_order = excluded.sort_order;`,
  )
}
lines.push('')

let order = 0
for (const p of managed) {
  order += 10
  const subSlug = slugify(p.sub)
  const price = p.purchasable && p.price ? p.price : 'null'
  const priceUnit = p.priceUnit ? q(p.priceUnit) : 'null'
  const subSel = `(select id from subcategories where world = ${q(p.world)} and slug = ${q(subSlug)})`
  lines.push(
    `insert into products (slug, name, world, subcategory_id, tag, story, specs, purchasable, price, price_unit, presentation, sort_order)\n` +
      `  values (${q(p.id)}, ${q(p.name)}, ${q(p.world)}, ${subSel}, ${q(p.tag)}, ${q(p.story ?? null)}, ${jsonb(p.specs)}, ${p.purchasable && p.price ? 'true' : 'false'}, ${price}, ${priceUnit}, 'swing', ${order})\n` +
      `  on conflict (slug) do update set name = excluded.name, world = excluded.world, subcategory_id = excluded.subcategory_id,\n` +
      `    tag = excluded.tag, story = excluded.story, specs = excluded.specs, purchasable = excluded.purchasable,\n` +
      `    price = excluded.price, price_unit = excluded.price_unit, sort_order = excluded.sort_order;`,
  )
  // images (photo visuals only) — replace per product for idempotency
  if (p.visual.kind === 'photo') {
    const prodSel = `(select id from products where slug = ${q(p.id)})`
    lines.push(`delete from product_images where product_id = ${prodSel};`)
    const imgs = [{ ...p.visual.cover, role: 'cover' }, ...(p.visual.gallery ?? []).map((g) => ({ ...g, role: 'gallery' }))]
    imgs.forEach((img, i) => {
      const src480 = img.src
      const src960 = img.src.replace('-480.webp', '-960.webp')
      lines.push(
        `insert into product_images (product_id, role, src_480, src_960, width, height, sort_order)\n` +
          `  values (${prodSel}, ${q(img.role)}, ${q(src480)}, ${q(src960)}, ${img.w}, ${img.h}, ${i});`,
      )
    })
  }
  lines.push('')
}

lines.push('commit;')
const sql = lines.join('\n')

await mkdir(path.join(ROOT, 'supabase'), { recursive: true })
await writeFile(path.join(ROOT, 'supabase/seed.sql'), sql)
console.log(`seed: wrote supabase/seed.sql (${subs.size} subcategories, ${managed.length} products)`)
